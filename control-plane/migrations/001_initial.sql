CREATE TABLE IF NOT EXISTS schema_version (version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS agents (id TEXT PRIMARY KEY, body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS nodes (id TEXT PRIMARY KEY, body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS tasks (
    id TEXT PRIMARY KEY, owner TEXT NOT NULL, idem_key TEXT NOT NULL,
    input_hash TEXT NOT NULL, body TEXT NOT NULL, UNIQUE(owner, idem_key)
);
CREATE TABLE IF NOT EXISTS events (
    task_id TEXT NOT NULL REFERENCES tasks(id), sequence INTEGER NOT NULL,
    body TEXT NOT NULL, PRIMARY KEY(task_id, sequence)
);
CREATE TABLE IF NOT EXISTS model_calls (
    id TEXT PRIMARY KEY, task_id TEXT NOT NULL REFERENCES tasks(id), body TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS model_calls_task ON model_calls(task_id);
CREATE TABLE IF NOT EXISTS audit (id TEXT PRIMARY KEY, body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS claims (id TEXT PRIMARY KEY, body TEXT NOT NULL);
